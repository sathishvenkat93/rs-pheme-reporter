def _enable_rls() -> None:
    from app.core.config import get_settings  # reads .env too, like the app's own URL

    password = get_settings().app_db_password.replace("'", "''")
    op.execute(f"""
        DO $$ BEGIN
          IF NOT EXISTS (SELECT FROM pg_roles WHERE rolname = 'pheme_app') THEN
            CREATE ROLE pheme_app LOGIN PASSWORD '{password}';
          END IF;
        END $$;
    """)
    op.execute("GRANT USAGE ON SCHEMA public TO pheme_app")
    op.execute("GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA public TO pheme_app")
    op.execute("REVOKE ALL ON alembic_version FROM pheme_app")
    op.execute("GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO pheme_app")
    op.execute("ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO pheme_app")
    op.execute("ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT USAGE, SELECT ON SEQUENCES TO pheme_app")
    op.execute("""
        CREATE OR REPLACE FUNCTION pheme_ws_ok(ws uuid) RETURNS boolean
        LANGUAGE sql STABLE AS $$
          SELECT coalesce(current_setting('app.bypass', true), '') = 'on'
              OR ws = nullif(current_setting('app.workspace_id', true), '')::uuid
        $$
    """)
    for table in (*WORKSPACE_TABLES, "workspaces"):
        column = "id" if table == "workspaces" else "workspace_id"
        op.execute(f"ALTER TABLE {table} ENABLE ROW LEVEL SECURITY")
        op.execute(f"ALTER TABLE {table} FORCE ROW LEVEL SECURITY")
        op.execute(f"CREATE POLICY workspace_isolation ON {table} USING (pheme_ws_ok({column})) "
                   f"WITH CHECK (pheme_ws_ok({column}))")


def _disable_rls() -> None:
    for table in (*WORKSPACE_TABLES, "workspaces"):
        op.execute(f"DROP POLICY IF EXISTS workspace_isolation ON {table}")
        op.execute(f"ALTER TABLE {table} NO FORCE ROW LEVEL SECURITY")
        op.execute(f"ALTER TABLE {table} DISABLE ROW LEVEL SECURITY")
    op.execute("DROP FUNCTION IF EXISTS pheme_ws_ok(uuid)")
    op.execute("ALTER DEFAULT PRIVILEGES IN SCHEMA public REVOKE ALL ON TABLES FROM pheme_app")
    op.execute("ALTER DEFAULT PRIVILEGES IN SCHEMA public REVOKE ALL ON SEQUENCES FROM pheme_app")
    op.execute("REVOKE ALL ON ALL TABLES IN SCHEMA public FROM pheme_app")
    op.execute("REVOKE ALL ON ALL SEQUENCES IN SCHEMA public FROM pheme_app")
    op.execute("REVOKE USAGE ON SCHEMA public FROM pheme_app")
    # The role is cluster-wide (other databases may use it), so it is not dropped here.


